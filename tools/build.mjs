// Validates the question bank and generates:
//   supabase/seed.sql          → paste into Supabase SQL editor (contains answers, never commit)
//   bank/build/questions.json  → used only by local demo mode (contains answers, never commit)
//
// Usage: node tools/build.mjs
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SESSIONS_DIR = join(ROOT, "bank", "sessions");
const POINTS = { easy: 1, medium: 2, hard: 3, extreme: 5 };
const TYPES = new Set(["single", "multi", "text"]);

const isIndex = (n, len) => Number.isInteger(n) && n >= 0 && n < len;

function validate(q, file) {
  const errors = [];
  const where = `${file} ${q.id ?? "(no id)"}`;
  if (!/^s\d{2}-q\d{2}$/.test(q.id ?? "")) errors.push("bad id");
  if (!Number.isInteger(q.session) || q.session < 0 || q.session > 99) errors.push("bad session");
  if (q.id && Number(q.id.slice(1, 3)) !== q.session) errors.push("id/session mismatch");
  if (!(q.difficulty in POINTS)) errors.push("bad difficulty");
  if (!TYPES.has(q.type)) errors.push("bad type");
  if (typeof q.prompt !== "string" || q.prompt.trim().length < 10) errors.push("prompt too short");
  if (typeof q.explanation !== "string" || q.explanation.trim().length < 20) errors.push("explanation too short");
  if (q.code != null && typeof q.code !== "string") errors.push("code must be a string");
  if (q.group != null && typeof q.group !== "string") errors.push("group must be a string");

  if (q.type === "single" || q.type === "multi") {
    const opts = q.options;
    if (!Array.isArray(opts) || opts.length < 3 || opts.length > 6 || opts.some((o) => typeof o !== "string" || !o.trim())) {
      errors.push("options must be 3-6 non-empty strings");
    } else if (new Set(opts.map((o) => o.trim())).size !== opts.length) {
      errors.push("duplicate options");
    }
    const len = Array.isArray(opts) ? opts.length : 0;
    if (q.type === "single" && !isIndex(q.answer, len)) errors.push("single answer must be a valid index");
    if (q.type === "multi") {
      const ok = Array.isArray(q.answer) && q.answer.length >= 2 && q.answer.every((i) => isIndex(i, len)) && new Set(q.answer).size === q.answer.length;
      if (!ok) errors.push("multi answer must be >=2 distinct valid indices");
    }
  }
  if (q.type === "text") {
    if (!Array.isArray(q.answer) || q.answer.length === 0 || q.answer.some((a) => typeof a !== "string" || !a.trim())) {
      errors.push("text answer must be a non-empty array of strings");
    }
    if (q.options && q.options.length) errors.push("text questions must not have options");
  }
  return errors.map((e) => `${where}: ${e}`);
}

function toRecord(q) {
  return {
    id: q.id,
    session: q.session,
    difficulty: q.difficulty,
    type: q.type,
    topic: (q.topic ?? "").trim(),
    prompt: q.prompt.trim(),
    code: (q.code ?? "").replace(/\s+$/, ""),
    options: q.type === "text" ? [] : q.options,
    shuffle: q.shuffle !== false,
    points: POINTS[q.difficulty],
    group: (q.group ?? "").trim(),
    answer: q.answer,
    explanation: q.explanation.trim(),
  };
}

// Dollar-quoting avoids any escaping problems with quotes/backslashes in code.
function dq(text) {
  let tag = "q";
  while (text.includes(`$${tag}$`)) tag += "x";
  return `$${tag}$${text}$${tag}$`;
}

function seedSql(records) {
  const rows = records.map((r) =>
    `(${dq(r.id)}, ${r.session}, ${dq(r.difficulty)}, ${dq(r.type)}, ${dq(r.topic)}, ${dq(r.prompt)}, ${dq(r.code)}, ${dq(JSON.stringify(r.options))}::jsonb, ${r.shuffle}, ${r.points}, ${dq(r.group)})`
  );
  const keys = records.map((r) => `(${dq(r.id)}, ${dq(JSON.stringify(r.answer))}::jsonb, ${dq(r.explanation)})`);
  const ids = records.map((r) => dq(r.id)).join(", ");
  return `-- GENERATED by tools/build.mjs — contains the ANSWER KEY. Do not commit or share.
-- ${records.length} questions. Re-running updates existing questions in place.
begin;
insert into public.questions (id, session, difficulty, type, topic, prompt, code, options, shuffle, points, grp) values
${rows.join(",\n")}
on conflict (id) do update set session = excluded.session, difficulty = excluded.difficulty, type = excluded.type,
  topic = excluded.topic, prompt = excluded.prompt, code = excluded.code, options = excluded.options,
  shuffle = excluded.shuffle, points = excluded.points, grp = excluded.grp, active = true;

insert into public.answer_keys (question_id, answer, explanation) values
${keys.join(",\n")}
on conflict (question_id) do update set answer = excluded.answer, explanation = excluded.explanation;

-- questions removed from the bank stop being drawn (kept for old results)
update public.questions set active = false where id not in (${ids});
commit;
`;
}

function main() {
  const files = readdirSync(SESSIONS_DIR).filter((f) => /^s\d{2}\.json$/.test(f)).sort();
  const records = [];
  const errors = [];
  const seen = new Set();
  for (const file of files) {
    let list;
    try {
      list = JSON.parse(readFileSync(join(SESSIONS_DIR, file), "utf8"));
    } catch (e) {
      errors.push(`${file}: invalid JSON (${e.message})`);
      continue;
    }
    if (!Array.isArray(list)) {
      errors.push(`${file}: top level must be an array`);
      continue;
    }
    for (const q of list) {
      errors.push(...validate(q, file));
      if (seen.has(q.id)) errors.push(`${file} ${q.id}: duplicate id`);
      seen.add(q.id);
      records.push(q);
    }
  }
  if (errors.length) {
    console.error(`✗ ${errors.length} problem(s):\n  ` + errors.join("\n  "));
    process.exit(1);
  }

  const out = records.map(toRecord);
  mkdirSync(join(ROOT, "bank", "build"), { recursive: true });
  writeFileSync(join(ROOT, "bank", "build", "questions.json"), JSON.stringify(out, null, 1));
  writeFileSync(join(ROOT, "supabase", "seed.sql"), seedSql(out));

  const by = (key) => out.reduce((m, r) => ((m[r[key]] = (m[r[key]] ?? 0) + 1), m), {});
  console.log(`✓ ${out.length} questions from ${files.length} files`);
  console.log("  by difficulty:", by("difficulty"));
  console.log("  by type:      ", by("type"));
  console.log("  by session:   ", by("session"));
  console.log("  wrote supabase/seed.sql and bank/build/questions.json");
}

main();
